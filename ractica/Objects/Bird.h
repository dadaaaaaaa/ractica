#pragma once
#include <glm/glm.hpp>

// Класс для управления поведением и анимацией птицы
class Bird {
private:
    // ============================================================================
    // ОСНОВНЫЕ ПАРАМЕТРЫ ПТИЦЫ
    // ============================================================================

    glm::vec3 position;           // Текущая позиция в мировых координатах
    glm::vec3 color;              // Цвет птицы для рендеринга
    float size;                   // Размер птицы (масштаб)
    float speed;                  // Скорость движения

    // ============================================================================
    // ПАРАМЕТРЫ АНИМАЦИИ КРЫЛЬЕВ
    // ============================================================================

    float wingAngle;              // Текущий угол крыла для анимации
    float wingSpeed;              // Скорость анимации крыльев

    // ============================================================================
    // ПАРАМЕТРЫ ДВИЖЕНИЯ И ПОВЕДЕНИЯ
    // ============================================================================

    glm::vec3 direction;          // Текущее направление движения
    glm::vec3 targetDirection;    // Целевое направление для плавного поворота
    float changeDirectionTimer;   // Таймер для смены направления
    float directionChangeInterval;// Интервал между сменами направления

public:
    // ============================================================================
    // КОНСТРУКТОР
    // ============================================================================

    // Создает птицу с указанными параметрами
    Bird(glm::vec3 pos = glm::vec3(0.0f),
        glm::vec3 col = glm::vec3(1.0f),
        float s = 1.0f,
        float sp = 1.0f);

    // ============================================================================
    // ОСНОВНЫЕ МЕТОДЫ ОБНОВЛЕНИЯ
    // ============================================================================

    // Обновляет состояние птицы (движение и анимация)
    void update(float deltaTime);

    // Обновляет анимацию взмахов крыльев
    void updateWingAnimation(float deltaTime);

    // ============================================================================
    // МЕТОДЫ УПРАВЛЕНИЯ ПОВЕДЕНИЕМ
    // ============================================================================

    // Генерирует случайное направление движения
    void generateRandomDirection();

    // Обновляет таймер смены направления
    void updateDirectionChange(float deltaTime);

    // Применяет легкую гравитацию для естественного движения
    void applyGravity(float deltaTime);

    // Проверяет границы и корректирует позицию птицы
    void checkBoundaries();

    // Сбрасывает птицу в начальное состояние
    void reset();

    // ============================================================================
    // СЕТТЕРЫ
    // ============================================================================

    // Устанавливает позицию птицы
    void setPosition(const glm::vec3& newPosition);

    // Устанавливает направление движения
    void setDirection(const glm::vec3& newDirection);

    // Устанавливает скорость движения
    void setSpeed(float newSpeed);

    // Устанавливает скорость анимации крыльев
    void setWingSpeed(float newWingSpeed);

    // Устанавливает цвет птицы
    void setColor(const glm::vec3& newColor);

    // Устанавливает размер птицы
    void setSize(float newSize);

    // ============================================================================
    // ГЕТТЕРЫ
    // ============================================================================

    // Возвращает текущую позицию птицы
    glm::vec3 getPosition() const { return position; }

    // Возвращает текущее направление движения
    glm::vec3 getDirection() const { return direction; }

    // Возвращает текущую скорость
    float getSpeed() const { return speed; }

    // Возвращает текущий угол крыла
    float getWingAngle() const { return wingAngle; }

    // Возвращает скорость анимации крыльев
    float getWingSpeed() const { return wingSpeed; }

    // Возвращает цвет птицы
    glm::vec3 getColor() const { return color; }

    // Возвращает размер птицы
    float getSize() const { return size; }

    // Возвращает целевое направление
    glm::vec3 getTargetDirection() const { return targetDirection; }

    // ============================================================================
    // ИНФОРМАЦИОННЫЕ МЕТОДЫ
    // ============================================================================

    // Проверяет, находится ли птица в активном состоянии
    bool isActive() const { return speed > 0.1f; }

    // Вычисляет расстояние до другой позиции
    float distanceTo(const glm::vec3& target) const;

    // Проверяет, находится ли птица в пределах радиуса от позиции
    bool isInRange(const glm::vec3& target, float radius) const;

    // ============================================================================
    // СЛУЖЕБНЫЕ МЕТОДЫ
    // ============================================================================

    // Выводит отладочную информацию о птице
    void printDebugInfo() const;

    // Сериализует данные птицы для сохранения
    void serialize() const;

    // Десериализует данные птицы из сохранения
    void deserialize();

private:
    // ============================================================================
    // ПРИВАТНЫЕ ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ
    // ============================================================================

    // Ограничивает угол крыла в допустимом диапазоне
    void clampWingAngle();

    // Нормализует направление движения
    void normalizeDirection();

    // Проверяет корректность параметров птицы
    bool validateParameters() const;
};